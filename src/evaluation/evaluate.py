
import os
import json

import pandas as pd
import soundfile as sf
import numpy as np

from .metrics import compute_all_standard_metrics
from .impulse_metrics import calculate_impulse_metrics
from .recovery_time import calculate_iisrt_and_rsdd


def _load_audio_mono(filepath: str):
    """Safely loads an audio file and ensures 1D float32 mono output."""

    data, sr = sf.read(
        filepath,
        dtype="float32"
    )

    if data.ndim > 1:
        data = np.mean(
            data,
            axis=1
        )

    return data.astype(np.float32), sr


def process_single_dict(
    meta: dict,
    data_root: str,
    system_label: str = "Impulse Guard"
) -> dict:

    if not isinstance(meta, dict):
        return None

    sample_id = meta.get("sample_id")
    split = meta.get(
        "split",
        "test"
    )

    if not sample_id:
        print(
            "[Skipping] Metadata has no sample_id."
        )
        return None

    # =========================================================
    # TEST SET ONLY
    # =========================================================

    if split != "test":
        return None

    # =========================================================
    # CURRENT MIXTURE METADATA FORMAT
    # =========================================================

    clean_rel = meta.get(
        "clean_path",
        ""
    )

    noisy_rel = meta.get(
        "noisy_path",
        ""
    )

    if not clean_rel or not noisy_rel:
        print(
            f"[Skipping] Sample {sample_id}: "
            f"missing clean_path or noisy_path."
        )
        return None

    # Metadata paths already begin with "data/..."
    clean_path = os.path.normpath(
        clean_rel
    )

    noisy_path = os.path.normpath(
        noisy_rel
    )

    # Enhanced audio generated by src/inference.py
    enhanced_path = os.path.normpath(
        os.path.join(
            data_root,
            "enhanced",
            "test",
            f"{sample_id}.wav"
        )
    )

    # =========================================================
    # FILE EXISTENCE CHECK
    # =========================================================

    if not os.path.exists(clean_path):
        print(
            f"[Missing WAV] {sample_id}: "
            f"Clean file not found:\n"
            f"  {clean_path}"
        )
        return None

    if not os.path.exists(noisy_path):
        print(
            f"[Missing WAV] {sample_id}: "
            f"Noisy file not found:\n"
            f"  {noisy_path}"
        )
        return None

    if not os.path.exists(enhanced_path):
        print(
            f"[Missing WAV] {sample_id}: "
            f"Enhanced file not found:\n"
            f"  {enhanced_path}"
        )
        return None

    # =========================================================
    # LOAD AUDIO
    # =========================================================

    try:

        clean, sr = _load_audio_mono(
            clean_path
        )

        noisy, noisy_sr = _load_audio_mono(
            noisy_path
        )

        enhanced, enhanced_sr = _load_audio_mono(
            enhanced_path
        )

    except Exception as e:

        print(
            f"[Audio load error] "
            f"{sample_id}: {e}"
        )
        return None

    # =========================================================
    # SAMPLE RATE VALIDATION
    # =========================================================

    if (
        noisy_sr != sr
        or enhanced_sr != sr
    ):

        print(
            f"[Skipping] {sample_id}: "
            f"sample-rate mismatch "
            f"(clean={sr}, "
            f"noisy={noisy_sr}, "
            f"enhanced={enhanced_sr})"
        )

        return None

    # =========================================================
    # LENGTH VALIDATION
    # =========================================================

    if (
        len(clean) == 0
        or len(noisy) == 0
        or len(enhanced) == 0
    ):

        print(
            f"[Skipping] {sample_id}: "
            f"one or more audio files are empty."
        )

        return None

    # =========================================================
    # MAKE ALL SIGNALS EQUAL LENGTH
    # =========================================================

    min_length = min(
        len(clean),
        len(noisy),
        len(enhanced)
    )

    clean = clean[:min_length]
    noisy = noisy[:min_length]
    enhanced = enhanced[:min_length]

    # =========================================================
    # NOISE INFORMATION
    # =========================================================

    noise_category = "unknown"
    noise_type = "unknown"

    mixture_type = str(
        meta.get(
            "mixture_type",
            ""
        )
    ).lower()

    noise_components = meta.get(
        "noise_components",
        []
    )

    categories = []
    types = []

    for noise in noise_components:

        if not isinstance(
            noise,
            dict
        ):
            continue

        category = str(
            noise.get(
                "category",
                ""
            )
        ).lower()

        noise_kind = str(
            noise.get(
                "type",
                ""
            )
        ).lower()

        if category:
            categories.append(
                category
            )

        if noise_kind:
            types.append(
                noise_kind
            )

    # =========================================================
    # IMPULSE INFORMATION
    # =========================================================

    impulse_info = meta.get(
        "impulse"
    )

    is_impulsive = (
        isinstance(
            impulse_info,
            dict
        )
        and bool(impulse_info)
    )

    # =========================================================
    # BUILD NOISE CATEGORY / TYPE
    # =========================================================

    # Clean mixtures intentionally have:
    # noise_components = []
    # impulse = null
    #
    # Therefore they must explicitly be classified as clean.

    if mixture_type == "clean":

        noise_category = "clean"
        noise_type = "clean"

    else:

        if categories:

            noise_category = "+".join(
                sorted(
                    set(categories)
                )
            )

        if types:

            noise_type = "+".join(
                sorted(
                    set(types)
                )
            )

        # Add impulsive component
        if is_impulsive:

            if noise_category == "unknown":

                noise_category = "impulsive"

            elif "impulsive" not in noise_category:

                noise_category += "+impulsive"

            if noise_type == "unknown":

                noise_type = "impulsive"

            elif "impulsive" not in noise_type:

                noise_type += "+impulsive"

    # =========================================================
    # BUILD RESULT RECORD
    # =========================================================

    target_snr = meta.get(
        "target_snr_db",
        np.nan
    )

    actual_snr = meta.get(
        "actual_snr_db",
        np.nan
    )

    # Convert JSON null to NaN explicitly
    if target_snr is None:
        target_snr = np.nan

    if actual_snr is None:
        actual_snr = np.nan

    record = {

        "sample_id": sample_id,

        "system": system_label,

        "split": split,

        "language": meta.get(
            "speech",
            {}
        ).get(
            "language",
            "unknown"
        ),

        "mixture_type": mixture_type,

        "noise_type": noise_type,

        "noise_category": noise_category,

        "is_impulsive": is_impulsive,

        "target_snr": target_snr,

        "actual_snr": actual_snr,

        "clean_path": clean_path,

        "noisy_path": noisy_path,

        "enhanced_path": enhanced_path,
    }

    # =========================================================
    # STANDARD SPEECH ENHANCEMENT METRICS
    # =========================================================

    try:

        std_metrics = compute_all_standard_metrics(
            clean,
            noisy,
            enhanced,
            sr=sr
        )

        if std_metrics:

            record.update(
                std_metrics
            )

    except Exception as e:

        print(
            f"[Standard metric warning] "
            f"{sample_id}: {e}"
        )

    # =========================================================
    # IMPULSE METRICS
    # =========================================================

    iisrt_list = []
    rsdd_list = []
    attenuation_list = []
    energy_list = []

    if is_impulsive:

        impulse_start = impulse_info.get(
            "impulse_onset_sample"
        )

        impulse_end = impulse_info.get(
            "impulse_offset_sample"
        )

        if (
            impulse_start is not None
            and impulse_end is not None
        ):

            impulse_start_sec = (
                float(impulse_start)
                / sr
            )

            impulse_end_sec = (
                float(impulse_end)
                / sr
            )

            # =================================================
            # IMPULSE ATTENUATION / RESIDUAL ENERGY
            # =================================================

            try:

                imp_stats = calculate_impulse_metrics(
                    noisy,
                    enhanced,
                    impulse_start_sec=impulse_start_sec,
                    impulse_end_sec=impulse_end_sec,
                    sr=sr
                )

                if (
                    "peak_attenuation_db"
                    in imp_stats
                ):

                    attenuation_list.append(
                        imp_stats[
                            "peak_attenuation_db"
                        ]
                    )

                if (
                    "residual_impulse_energy_ratio"
                    in imp_stats
                ):

                    energy_list.append(
                        imp_stats[
                            "residual_impulse_energy_ratio"
                        ]
                    )

            except Exception as e:

                print(
                    f"[Impulse metric warning] "
                    f"{sample_id}: {e}"
                )

            # =================================================
            # RECOVERY TIME
            # =================================================

            try:

                rec_stats = calculate_iisrt_and_rsdd(
                    clean,
                    enhanced,
                    impulse_start_sec=impulse_start_sec,
                    impulse_end_sec=impulse_end_sec,
                    sr=sr
                )

                if (
                    "iisrt_ms"
                    in rec_stats
                    and not np.isnan(
                        rec_stats["iisrt_ms"]
                    )
                ):

                    iisrt_list.append(
                        rec_stats[
                            "iisrt_ms"
                        ]
                    )

                if (
                    "rsdd_ms"
                    in rec_stats
                    and not np.isnan(
                        rec_stats["rsdd_ms"]
                    )
                ):

                    rsdd_list.append(
                        rec_stats[
                            "rsdd_ms"
                        ]
                    )

            except Exception as e:

                print(
                    f"[Recovery metric warning] "
                    f"{sample_id}: {e}"
                )

    # =========================================================
    # IMPULSE SUMMARY VALUES
    # =========================================================

    record[
        "peak_attenuation_db_mean"
    ] = (

        float(
            np.mean(
                attenuation_list
            )
        )

        if attenuation_list

        else np.nan
    )

    record[
        "residual_energy_ratio_mean"
    ] = (

        float(
            np.mean(
                energy_list
            )
        )

        if energy_list

        else np.nan
    )

    record[
        "iisrt_mean_ms"
    ] = (

        float(
            np.mean(
                iisrt_list
            )
        )

        if iisrt_list

        else np.nan
    )

    record[
        "rsdd_mean_ms"
    ] = (

        float(
            np.mean(
                rsdd_list
            )
        )

        if rsdd_list

        else np.nan
    )

    return record


def run_evaluation_suite(
    metadata_dir: str,
    data_root: str,
    output_csv: str,
    system_label: str = "Impulse Guard"
):

    results = []

    # =========================================================
    # DEBUG LIMIT
    # =========================================================

    # For now evaluate only 10 valid test samples.
    # Remove this limit after evaluation logic is verified.

    max_samples = 3000
    processed_samples = 0

    # =========================================================
    # READ METADATA
    # =========================================================

    for root, _, files in os.walk(
        metadata_dir
    ):

        for file in files:

            full_path = os.path.join(
                root,
                file
            )

            # =================================================
            # JSONL METADATA
            # =================================================

            if file.endswith(".jsonl"):

                with open(
                    full_path,
                    "r",
                    encoding="utf-8"
                ) as f:

                    for line_num, line in enumerate(
                        f,
                        1
                    ):

                        # Stop after requested number
                        # of valid samples.

                        if (
                            processed_samples
                            >= max_samples
                        ):
                            break

                        line = line.strip()

                        if not line:
                            continue

                        try:

                            meta = json.loads(
                                line
                            )

                            # ---------------------------------
                            # TEST SET ONLY
                            # ---------------------------------

                            if meta.get(
                                "split"
                            ) != "test":

                                continue

                            sample_id = meta.get(
                                "sample_id",
                                "unknown"
                            )

                            # ---------------------------------
                            # PROGRESS
                            # ---------------------------------

                            print(
                                f"\n[Evaluating "
                                f"{processed_samples + 1}/"
                                f"{max_samples}] "
                                f"{sample_id}",
                                flush=True
                            )

                            # ---------------------------------
                            # PROCESS SAMPLE
                            # ---------------------------------

                            res = process_single_dict(
                                meta,
                                data_root,
                                system_label=system_label
                            )

                            # ---------------------------------
                            # STORE RESULT
                            # ---------------------------------

                            if res is not None:

                                results.append(
                                    res
                                )

                                processed_samples += 1

                                print(
                                    f"[Completed] "
                                    f"{sample_id}",
                                    flush=True
                                )

                            else:

                                print(
                                    f"[Skipped] "
                                    f"{sample_id}",
                                    flush=True
                                )

                        except Exception as e:

                            print(
                                f"Error parsing line "
                                f"{line_num} in "
                                f"{full_path}: {e}",
                                flush=True
                            )

                    # Stop processing files once
                    # enough samples have been evaluated.

                    if (
                        processed_samples
                        >= max_samples
                    ):
                        break

            # =================================================
            # STANDARD JSON
            # =================================================

            elif file.endswith(".json"):

                # Main mixture metadata is JSONL.
                # Ignore standalone JSON files.

                continue

        # =====================================================
        # STOP OUTER DIRECTORY LOOP
        # =====================================================

        if (
            processed_samples
            >= max_samples
        ):
            break

    # =========================================================
    # CREATE DATAFRAME
    # =========================================================

    df = pd.DataFrame(
        results
    )

    # =========================================================
    # SAVE RESULTS
    # =========================================================

    output_dir = os.path.dirname(
        output_csv
    )

    if output_dir:

        os.makedirs(
            output_dir,
            exist_ok=True
        )

    df.to_csv(
        output_csv,
        index=False
    )

    # =========================================================
    # EVALUATION SUMMARY
    # =========================================================

    print(
        "\n================ EVALUATION SUMMARY ================"
    )

    print(
        f"Valid test samples processed: "
        f"{len(df)}"
    )

    # =========================================================
    # NO RESULTS
    # =========================================================

    if df.empty:

        print(
            "No valid test evaluation samples were processed."
        )

        print(
            "Check that clean, noisy, and enhanced "
            "test WAV files exist."
        )

        print(
            "====================================================\n"
        )

        return

    # =========================================================
    # STANDARD METRICS
    # =========================================================

    summary_cols = [

        col

        for col in [

            "si_snr_improvement",

            "si_sdr_improvement",

            "stoi_improvement",

            "pesq_improvement"

        ]

        if col in df.columns
    ]

    # =========================================================
    # SEPARATE CLEAN CONTROL SAMPLES
    # =========================================================

    clean_df = df[
        df["noise_category"] == "clean"
    ]

    noisy_df = df[
        df["noise_category"] != "clean"
    ]

    # =========================================================
    # OVERALL NOISY TEST METRICS
    # =========================================================

    if (
        summary_cols
        and not noisy_df.empty
    ):

        print(
            "\nOverall Test-Set "
            "Speech Enhancement Metrics "
            "(Noisy Samples Only):"
        )

        print(
            noisy_df[
                summary_cols
            ].mean(
                numeric_only=True
            )
        )

    # =========================================================
    # CLEAN CONTROL METRICS
    # =========================================================

    if (
        summary_cols
        and not clean_df.empty
    ):

        print(
            "\nClean-Input Control Metrics:"
        )

        print(
            f"Clean samples: "
            f"{len(clean_df)}"
        )

        print(
            clean_df[
                summary_cols
            ].mean(
                numeric_only=True
            )
        )

    # =========================================================
    # CONTINUOUS / NON-IMPULSIVE NOISE
    # =========================================================

    if "is_impulsive" in df.columns:

        non_imp = df[
            (
                df["is_impulsive"]
                == False
            )
            & (
                df["noise_category"]
                != "clean"
            )
        ]

        if (
            not non_imp.empty
            and summary_cols
        ):

            print(
                "\nContinuous / "
                "Non-Impulsive Noise Metrics:"
            )

            print(
                non_imp[
                    summary_cols
                ].mean(
                    numeric_only=True
                )
            )

    # =========================================================
    # IMPULSIVE NOISE
    # =========================================================

    if "is_impulsive" in df.columns:

        imp = df[
            df["is_impulsive"]
            == True
        ]

        print(
            "\nImpulsive Noise Events:"
        )

        print(
            f"Samples: "
            f"{len(imp)}"
        )

        if not imp.empty:

            impulse_cols = [

                c

                for c in [

                    "peak_attenuation_db_mean",

                    "residual_energy_ratio_mean",

                    "iisrt_mean_ms",

                    "rsdd_mean_ms"

                ]

                if c in imp.columns
            ]

            if impulse_cols:

                print(
                    imp[
                        impulse_cols
                    ].mean(
                        numeric_only=True
                    )
                )

    # =========================================================
    # NOISE CATEGORY BREAKDOWN
    # =========================================================

    if (
        "noise_category" in df.columns
        and summary_cols
    ):

        print(
            "\nMetrics by Noise Category:"
        )

        # Exclude clean control samples.
        noise_only_df = df[
            df["noise_category"]
            != "clean"
        ]

        if not noise_only_df.empty:

            category_summary = (

                noise_only_df
                .groupby(
                    "noise_category"
                )[summary_cols]
                .mean(
                    numeric_only=True
                )
                .round(4)
            )

            print(
                category_summary.to_string()
            )

        else:

            print(
                "No noisy samples available."
            )

    # =========================================================
    # SNR BREAKDOWN
    # =========================================================

    if (
        "target_snr" in df.columns
        and summary_cols
    ):

        print(
            "\nMetrics by Target SNR:"
        )

        # Remove clean samples and samples
        # where target SNR is undefined.

        snr_df = df[
            (
                df["noise_category"]
                != "clean"
            )
            & (
                df["target_snr"]
                .notna()
            )
        ]

        if not snr_df.empty:

            snr_summary = (

                snr_df
                .groupby(
                    "target_snr"
                )[summary_cols]
                .mean(
                    numeric_only=True
                )
                .round(4)
            )

            print(
                snr_summary.to_string()
            )

        else:

            print(
                "No valid noisy SNR samples available."
            )

    # =========================================================
    # FINISH
    # =========================================================

    print(
        "====================================================\n"
    )